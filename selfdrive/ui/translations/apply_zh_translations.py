def apply(lang_code: str, translations: dict[str, str]) -> int:
  po_path = f"selfdrive/ui/translations/app_{lang_code}.po"
  header, entries = parse_po(po_path)
  filled = 0
  for entry in entries:
    if not entry.msgstr.strip() and entry.msgid in translations:
      entry.msgstr = translations[entry.msgid]
      filled += 1
  write_po(po_path, header, entries)
  return filled


